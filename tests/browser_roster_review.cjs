// Chromium UI checks on disposable compose.runtime.yaml only.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const base = 'http://app:8000';
const artifacts = process.env.AUDIT_ARTIFACTS || '/artifacts';

(async () => {
  const browser = await chromium.launch({headless: true, args: ['--no-sandbox']});
  const errors = [];
  const checks = [];
  fs.mkdirSync(artifacts, {recursive: true});
  try {
    const page = await browser.newPage({viewport: {width: 1280, height: 900}});
    page.on('pageerror', error => errors.push(error.message));
    await page.goto(base + '/teacher/login');
    await page.locator('[name=username]').fill('review_audit');
    await page.locator('[name=password]').fill('synthetic-review-password');
    await page.locator('button[type=submit]').click();
    await page.waitForURL('**/teacher/dashboard');
    await page.goto(base + '/teacher/roster-sync#tab-sync');
    await page.locator('#tab-pane-sync').waitFor({state: 'visible'});
    assert((await page.locator('#tab-pane-sync').innerText()).includes('Спочатку підтвердьте відповідний клас'));
    const classForm = page.locator('.roster-resolution-form').first();
    assert.equal(await classForm.locator('[name=native_id] option:checked').innerText(), '7-А · збіг ПІБ · ID 1');
    await classForm.getByRole('button', {name: 'Підтвердити прив’язку'}).click();
    await page.locator('#tab-pane-sync').waitFor({state: 'visible'});
    assert.equal(await page.locator('.roster-resolution-form').count(), 3);
    const first = page.locator('.roster-resolution-form').filter({has: page.locator('option:checked', {hasText: 'Коваленко Ірина'})});
    const options = await first.locator('[name=native_id] option').allTextContents();
    assert.equal(options.length, 3);
    assert(!options.some(value => value.includes('Чужий')));
    await first.locator('.roster-candidate-search').fill('Шевченко');
    assert.equal(await first.locator('[name=native_id] option').count(), 3);
    await first.locator('.roster-candidate-search').fill('відсутній');
    assert.equal(await first.locator('[name=native_id] option').count(), 2);
    await first.locator('.roster-candidate-search').fill('');
    checks.push('Class confirmed first; pupil suggestions are limited to its class; search keeps the current selection');
    await page.screenshot({path: artifacts + '/sync_desktop.png', fullPage: true});
    await page.setViewportSize({width: 390, height: 844});
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
    await page.screenshot({path: artifacts + '/sync_mobile.png', fullPage: true});
    await page.getByRole('button', {name: 'Підтвердити точні збіги (2)'}).click();
    await page.locator('#tab-pane-sync').waitFor({state: 'visible'});
    assert((await page.locator('body').innerText()).includes('Знайдені відповідності підтверджено'));
    assert.equal(await page.locator('.roster-resolution-form').count(), 1);
    const newPupil = page.locator('.roster-resolution-form');
    await newPupil.locator('[name=create]').check();
    assert(await newPupil.locator('[name=native_id]').isDisabled());
    assert.equal(await newPupil.locator('[name=choice]').inputValue(), '0');
    await newPupil.getByRole('button', {name: 'Підтвердити прив’язку'}).click();
    await page.locator('#tab-pane-sync').waitFor({state: 'visible'});
    assert.equal(await page.locator('.roster-resolution-form').count(), 0);
    assert((await page.locator('#tab-pane-sync').innerText()).includes('Списки узгоджено'));
    checks.push('Bulk confirms two exact pairs; explicit creation clears binding and selects received data; ready records are collapsed');
    await page.getByRole('tab', {name: /Окремі учні/}).click();
    assert((await page.locator('#tab-pane-outside').innerText()).includes('Активних спроб: 1'));
    assert((await page.locator('#tab-pane-outside').innerText()).includes('В архіві: 1'));
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
    await page.screenshot({path: artifacts + '/outside_mobile.png', fullPage: true});
    await page.getByRole('link', {name: 'Архів (1)', exact: true}).click();
    await page.waitForURL('**/teacher/results?pupil_scope=outside&tab=archive');
    assert.equal(await page.locator('h1').innerText(), 'Результати окремих учнів');
    const exportLink = await page.locator('a[href^="/teacher/results/export"]').getAttribute('href');
    assert(exportLink.includes('pupil_scope=outside') && exportLink.includes('tab=archive'));
    const csv = await (await page.request.get(base + exportLink)).text();
    assert(csv.includes('Архівний Учень'));
    assert(!csv.includes('Окремий Учень'));
    assert(!csv.includes('Коваленко'));
    await page.getByRole('link', {name: '← До окремих учнів', exact: true}).click();
    await page.locator('#tab-pane-outside').waitFor({state: 'visible'});
    await page.reload();
    await page.locator('#tab-pane-outside').waitFor({state: 'visible'});
    checks.push('Outside tab explains active/archive results; archive CSV keeps scope; return link and refresh preserve the tab');
    await page.goto(base + '/teacher/about');
    const { version } = await (await page.request.get(base + '/api/version')).json();
    assert((await page.locator('body').innerText()).includes(version));
    assert.deepEqual(errors, []);
    fs.writeFileSync(artifacts + '/browser_checks.json', JSON.stringify({passed: checks, javascript_errors: errors}, null, 2));
    console.log(JSON.stringify({passed: checks.length, checks, javascript_errors: errors}, null, 2));
  } finally { await browser.close(); }
})().catch(error => {console.error(error); process.exitCode = 1;});
